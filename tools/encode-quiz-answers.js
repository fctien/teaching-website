#!/usr/bin/env node
// Extracts quiz answers from data.js and encodes them into a separate
// obfuscated file. Replaces `answer: N` with removal from client data.
//
// Usage: node tools/encode-quiz-answers.js
// Output: js/quiz-key.js (loaded separately, answers encoded)

const fs = require("fs");
const path = require("path");

const dataPath = path.join(__dirname, "..", "js", "data.js");
let src = fs.readFileSync(dataPath, "utf8");

// Extract all answer values and build an answer key
const answerKey = {};
const courseRegex = /course(\d+):\s*\{/g;

// Parse quizData to extract answers per course/lang
// We'll use a simpler approach: regex to find answer patterns
const lines = src.split("\n");
let currentCourse = null;
let currentLang = null;
let questionIndex = 0;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];

  // Detect we've left quizData
  if (/^const homeworkData/.test(line)) break;

  const courseMatch = line.match(/^\s*(course\d+):\s*\{/);
  if (courseMatch) {
    currentCourse = courseMatch[1];
    answerKey[currentCourse] = {};
    continue;
  }

  const langMatch = line.match(/^\s*(zh|en):\s*\[/);
  if (langMatch && currentCourse) {
    currentLang = langMatch[1];
    answerKey[currentCourse][currentLang] = [];
    questionIndex = 0;
    continue;
  }

  const ansMatch = line.match(/^\s*answer:\s*(\d+)/);
  if (ansMatch && currentCourse && currentLang) {
    answerKey[currentCourse][currentLang].push(parseInt(ansMatch[1]));
  }
}

// Encode the answer key with simple XOR obfuscation
const keyJson = JSON.stringify(answerKey);
const xorKey = 42;
const encoded = Buffer.from(keyJson).map(b => b ^ xorKey).toString("base64");

// Write quiz-key.js
const output = `// Quiz answer key (encoded) — do not edit manually
// Generated by tools/encode-quiz-answers.js
const _qk = "${encoded}";
function _dqk() {
  const raw = atob(_qk);
  const bytes = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) bytes[i] = raw.charCodeAt(i) ^ 42;
  return JSON.parse(new TextDecoder().decode(bytes));
}
`;
fs.writeFileSync(path.join(__dirname, "..", "js", "quiz-key.js"), output, "utf8");

// Remove answer fields from data.js
const cleaned = src.replace(/^(\s*)answer:\s*\d+,?\s*$/gm, "");
fs.writeFileSync(dataPath, cleaned, "utf8");

console.log("Answer key extracted to js/quiz-key.js");
console.log("Answer fields removed from js/data.js");
console.log(`Courses processed: ${Object.keys(answerKey).join(", ")}`);
